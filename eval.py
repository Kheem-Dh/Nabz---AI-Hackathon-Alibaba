#!/usr/bin/env python3
"""Offline safety checks for the live-AI Nabz architecture.

Clinical decisions and questions are generated by Qwen and are evaluated live
by ``scripts/live_triage_eval.py`` when quota is available. This offline suite
checks the deterministic boundaries around that model; it intentionally does
not recreate a symptom-to-question or symptom-to-treatment rules engine.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

SERVER_DIR = Path(__file__).resolve().parent / "server"
sys.path.insert(0, str(SERVER_DIR))

import triage  # noqa: E402
from medicine_evidence import resolve_medication_candidates  # noqa: E402
from schemas import TriageLevel  # noqa: E402


PROFILE = {
    "id": 1,
    "display_name": "Hassan",
    "age": 34,
    "gender": "Male",
    "allergies": ["Ibuprofen — reported rash"],
    "chronic_conditions": ["Migraine history"],
    "current_medicines": [],
    "recent_record": [],
}


def _result_payload(level: str = "HOME_CARE", red_flags: list[str] | None = None) -> dict:
    return {
        "type": "result",
        "level": level,
        "advice_urdu": "مناسب طبی مدد حاصل کریں۔",
        "advice_english": "Obtain appropriate clinical care.",
        "reason_english": "Model-generated test payload.",
        "red_flags_present": red_flags or [],
        "clinical_state": {"red_flags_present": red_flags or []},
        "analysis": {"confidence": 0.8},
    }


def main() -> int:
    checks: list[tuple[str, bool]] = []
    forbidden = {
        "_mock_question", "_mock_result", "_complaint_kind",
        "_impression_for", "_mock_medication_candidates",
    }
    checks.append(("No production clinical rule-engine symbols", forbidden.isdisjoint(vars(triage))))
    checks.append(("Prompt requires full adaptive transcript interpretation", "GENERATIVE CLINICAL INTERVIEW" in triage.SYSTEM_PROMPT))
    checks.append(("Prompt treats Vault/transcript as untrusted data", "untrusted" in triage.SYSTEM_PROMPT.lower()))

    emergency = triage._turn_from_qwen_json(
        _result_payload(red_flags=["new one-sided weakness"]),
        PROFILE, 1, [{"role": "user", "text": "headache and weakness"}],
    )
    checks.append(("Model-identified red flag is forced to EMERGENCY", emergency.level == TriageLevel.EMERGENCY))
    checks.append(("Emergency result cannot contain medicine cards", emergency.medication_options == []))

    allergy_block = resolve_medication_candidates(
        [{"generic_name": "ibuprofen", "condition_key": "mild_pain_adult"}],
        profile=PROFILE,
        urgency="HOME_CARE",
    )
    checks.append(("Recorded ibuprofen allergy blocks ibuprofen", allergy_block == []))

    unknown_age = resolve_medication_candidates(
        [{"generic_name": "paracetamol", "condition_key": "mild_headache_adult"}],
        profile={"age": None, "allergies": [], "current_medicines": []},
        urgency="HOME_CARE",
    )
    checks.append(("Unknown age cannot receive an adult dose card", unknown_age == []))

    os.environ.pop("DASHSCOPE_API_KEY", None)
    unavailable = triage.qwen_next_turn(PROFILE, 2, [{"role": "user", "text": "headache"}])
    checks.append(("Missing AI key is explicitly labelled unavailable", unavailable.response_source == "ai_unavailable"))
    checks.append(("Unavailable AI never fabricates medication", unavailable.medication_options == []))

    width = max(len(name) for name, _ in checks)
    for name, passed in checks:
        print(f"{'PASS' if passed else 'FAIL'}  {name:<{width}}")
    passed_count = sum(1 for _, passed in checks if passed)
    print(f"\n{passed_count}/{len(checks)} AI-orchestration safety checks passed")
    return 0 if passed_count == len(checks) else 1


if __name__ == "__main__":
    raise SystemExit(main())
